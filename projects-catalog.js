  const mapByName = new Map();
  const mapById = new Map();

  projects.forEach(p => {
    mapByName.set(p.name.toLowerCase().trim(), p);
    mapById.set(p.id.toLowerCase().trim(), p);
    if (p.planetId) {
      mapByName.set(p.planetId.toLowerCase().trim(), p);
    }
  });

  return {
    categories,
    projects,
    getProjectByName: function (name) {
      if (!name) return null;
      return mapByName.get(name.toLowerCase().trim()) || null;
    },
    getProjectById: function (id) {
      if (!id) return null;
      return mapById.get(id.toLowerCase().trim()) || null;
    },
    getProjectsByCategory: function (catIdOrName) {
      if (!catIdOrName || catIdOrName.toLowerCase() === 'all') return projects;
      const lower = catIdOrName.toLowerCase();
      return projects.filter(p => p.categoryId.toLowerCase() === lower || p.category.toLowerCase() === lower);
    },
    getHighlights: function () {
      return projects.filter(p => p.highlight);
    }
  };
